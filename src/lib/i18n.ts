/** Language the chrome renders in: under auto that's whatever was last heard. */
export function uiLanguage(selected: string, detected: string | null): string {
  if (selected === 'auto') return detected && UI_STRINGS[detected] ? detected : 'en'
  return UI_STRINGS[selected] ? selected : 'en'
}

export function strings(lang: string): UIStrings {
  return UI_STRINGS[lang] ?? UI_STRINGS['en']!
}

/** Per-key lookup that falls back to English rather than rendering `undefined`. */
export function t(lang: string, key: keyof UIStrings): string {
  return UI_STRINGS[lang]?.[key] ?? UI_STRINGS['en']![key]
}

